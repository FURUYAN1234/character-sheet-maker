import { buildCharacterInfoEntries } from './prompt.js';

const CANVAS_WIDTH = 1024;
const ARTWORK_HEIGHT = 1536;
const HORIZONTAL_PADDING = 32;
const COLUMN_GAP = 28;
const LABEL_WIDTH = 86;
const VALUE_FONT = '16px "Yu Gothic UI", Meiryo, sans-serif';
const LABEL_FONT = '600 14px "Yu Gothic UI", Meiryo, sans-serif';
const TITLE_FONT = '700 28px "Yu Gothic UI", Meiryo, sans-serif';
const BODY_LINE_HEIGHT = 21;
const TITLE_LINE_HEIGHT = 34;

const wrapText = (context, text, maxWidth) => {
  const paragraphs = String(text ?? '').split(/\r?\n/);
  return paragraphs.flatMap((paragraph) => {
    if (!paragraph) return [''];

    const lines = [];
    let line = '';
    for (const character of Array.from(paragraph)) {
      const nextLine = line + character;
      if (line && context.measureText(nextLine).width > maxWidth) {
        lines.push(line);
        line = character;
      } else {
        line = nextLine;
      }
    }
    lines.push(line);
    return lines;
  });
};

const createRows = (context, entries, columnWidth) => {
  const rows = [];
  for (let index = 0; index < entries.length; index += 2) {
    const cells = entries.slice(index, index + 2).map(({ label, value }) => ({
      label,
      valueLines: wrapText(context, value, columnWidth - LABEL_WIDTH - 8),
    }));
    const maxLines = Math.max(...cells.map(({ valueLines }) => valueLines.length));
    rows.push({ cells, height: maxLines * BODY_LINE_HEIGHT + 8 });
  }
  return rows;
};

export const composeCharacterSheet = (base64DataUrl, formData, systemVersion = '') => new Promise((resolve, reject) => {
  const image = new Image();
  image.onload = () => {
    const canvas = document.createElement('canvas');
    canvas.width = CANVAS_WIDTH;
    canvas.height = 1;
    let context = canvas.getContext('2d');
    if (!context) {
      reject(new Error('画像合成用キャンバスを初期化できませんでした。'));
      return;
    }

    const entries = buildCharacterInfoEntries(formData);
    const nameEntry = entries[0];
    const infoEntries = entries.slice(1);
    const columnWidth = (CANVAS_WIDTH - HORIZONTAL_PADDING * 2 - COLUMN_GAP) / 2;
    context.font = VALUE_FONT;
    const rows = createRows(context, infoEntries, columnWidth);
    context.font = TITLE_FONT;
    const titleLines = wrapText(context, nameEntry.value, CANVAS_WIDTH - HORIZONTAL_PADDING * 2);
    const titleTop = 42;
    let rowTop = titleTop + titleLines.length * TITLE_LINE_HEIGHT + 12;
    for (const row of rows) rowTop += row.height;
    const headerHeight = Math.ceil(rowTop + 22);

    canvas.height = headerHeight + ARTWORK_HEIGHT;
    context = canvas.getContext('2d');
    if (!context) {
      reject(new Error('画像合成用キャンバスを初期化できませんでした。'));
      return;
    }

    context.fillStyle = '#FFFFFF';
    context.fillRect(0, 0, canvas.width, canvas.height);

    const scale = Math.min(
      CANVAS_WIDTH / image.naturalWidth,
      ARTWORK_HEIGHT / image.naturalHeight,
    );
    const drawWidth = image.naturalWidth * scale;
    const drawHeight = image.naturalHeight * scale;
    const offsetX = (CANVAS_WIDTH - drawWidth) / 2;
    const offsetY = (ARTWORK_HEIGHT - drawHeight) / 2;
    context.drawImage(image, offsetX, headerHeight + offsetY, drawWidth, drawHeight);

    context.textAlign = 'left';
    context.textBaseline = 'top';
    context.fillStyle = '#64748B';
    context.font = LABEL_FONT;
    context.fillText('キャラクター情報', HORIZONTAL_PADDING, 16);

    context.fillStyle = '#0F172A';
    context.font = TITLE_FONT;
    titleLines.forEach((line, index) => {
      context.fillText(line, HORIZONTAL_PADDING, titleTop + index * TITLE_LINE_HEIGHT);
    });

    const columnX = [HORIZONTAL_PADDING, HORIZONTAL_PADDING + columnWidth + COLUMN_GAP];
    let currentY = titleTop + titleLines.length * TITLE_LINE_HEIGHT + 12;
    for (const row of rows) {
      row.cells.forEach(({ label, valueLines }, cellIndex) => {
        const x = columnX[cellIndex];
        context.font = LABEL_FONT;
        context.fillStyle = '#475569';
        context.fillText(`■${label}`, x, currentY);
        context.font = VALUE_FONT;
        context.fillStyle = '#0F172A';
        valueLines.forEach((line, lineIndex) => {
          context.fillText(line, x + LABEL_WIDTH, currentY + lineIndex * BODY_LINE_HEIGHT);
        });
      });
      currentY += row.height;
    }

    const dividerY = headerHeight - 10;
    context.beginPath();
    context.strokeStyle = '#CBD5E1';
    context.lineWidth = 1;
    context.moveTo(HORIZONTAL_PADDING, dividerY);
    context.lineTo(CANVAS_WIDTH - HORIZONTAL_PADDING, dividerY);
    context.stroke();

    const watermarkText = systemVersion
      ? `Generated by Super FURU AI Character Sheet v${systemVersion}`
      : 'Generated by Super FURU AI Character Sheet';
    context.font = '14px "Segoe UI", Arial, sans-serif';
    context.textAlign = 'right';
    context.textBaseline = 'bottom';
    context.strokeStyle = 'rgba(255, 255, 255, 0.8)';
    context.lineWidth = 3;
    context.strokeText(watermarkText, CANVAS_WIDTH - 8, canvas.height - 8);
    context.fillStyle = 'rgba(40, 40, 40, 0.9)';
    context.fillText(watermarkText, CANVAS_WIDTH - 8, canvas.height - 8);

    resolve(canvas.toDataURL('image/png'));
  };
  image.onerror = () => reject(new Error('生成画像の読み込みに失敗しました。'));
  image.src = base64DataUrl;
});
